export function auditLabel(action: string, locale: "ar" | "en") {
  const i = locale === "ar" ? 0 : 1;
  if (A[action]) return A[action][i];
  const [g] = action.split(".");
  const group = GROUP[g]?.[i];
  return group ? `${group}: ${action.slice(g.length + 1).replace(/_/g, " ")}` : action;
}

